#!/usr/bin/env python3
"""Generate the checked-in SDK from the repository's Rocksky lexicons."""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent.parent / 'apps/api/lexicons'
lexicons = [json.loads(path.read_text()) for path in sorted(SOURCE.rglob('*.json'))]
def cap(s):
    return s[0].upper() + s[1:]
def name(nsid, key):
    return ''.join(map(cap, nsid.split('.')[2:])) + cap(key)
def label(s):
    return json.dumps(s)
defs = {(lex['id'], key): value for lex in lexicons for key, value in lex['defs'].items()
        if value['type'] not in ('query', 'procedure')}

def render(schema, nsid, stack=()):
    kind = schema['type']
    if kind in ('string', 'token'): return 'String'
    if kind == 'boolean': return 'Boolean'
    # Lexicon integers are safe JS integers, not restricted to PureScript's Int32.
    if kind in ('integer', 'number'): return 'Number'
    if kind == 'array': return 'Array (' + render(schema['items'], nsid, stack) + ')'
    if kind == 'record': return render(schema['record'], nsid, stack)
    if kind == 'ref':
        ref = schema['ref']
        target, _, key = ref.partition('#')
        target, key = target or nsid, key or 'main'
        if (target, key) not in defs:
            raise ValueError('Unresolved reference: ' + ref)
        # Recursive references and open unions remain inspectable raw JSON.
        if (target, key) in stack: return 'Json'
        # Inline recursive definitions to avoid recursive type synonyms.
        return render(defs[target, key], target, stack + ((target, key),))
    if kind in ('object', 'params'):
        required = set(schema.get('required', [])) - set(schema.get('nullable', []))
        props = []
        for key, prop in schema.get('properties', {}).items():
            typ = render(prop, nsid, stack)
            if key not in required: typ = 'Maybe (' + typ + ')'
            props.append(label(key) + ' :: ' + typ)
        return '{ ' + ', '.join(props) + ' }'
    if kind in ('union', 'unknown', 'blob', 'bytes', 'cid-link'): return 'Json'
    raise ValueError('Unsupported schema type: ' + kind)

# Use shared aliases at endpoint boundaries; expand references inside these aliases
# so even recursive schemas remain valid type synonyms.
def boundary(schema, nsid):
    if schema.get('type') == 'ref':
        target, _, key = schema['ref'].partition('#')
        return 'Types.' + name(target or nsid, key or 'main')
    return render(schema, nsid)

def optional_paths(schema, nsid, path=(), stack=()):
    kind = schema['type']
    if kind == 'ref':
        target, _, key = schema['ref'].partition('#')
        target, key = target or nsid, key or 'main'
        if (target, key) in stack: return []
        return optional_paths(defs[target,key], target, path, stack + ((target,key),))
    if kind == 'array': return optional_paths(schema['items'], nsid, path + ('*',), stack)
    paths = []
    if kind in ('object', 'params'):
        for key, prop in schema.get('properties', {}).items():
            child = path + (key,)
            if key not in schema.get('required', []): paths.append(child)
            paths.extend(optional_paths(prop, nsid, child, stack))
    return paths

def defaults(schema, nsid, typ, func):
    if schema.get('type') not in ('object', 'params'): return ''
    props = schema.get('properties', {})
    required = set(schema.get('required', [])) - set(schema.get('nullable', []))
    args = {k:v for k,v in props.items() if k in required}
    argtype = render({'type':'object', 'properties':args, 'required':list(args)}, nsid)
    values = [label(k) + ': ' + ('required.' + label(k) if k in required else 'Nothing') for k in props]
    return '\n' + func + ' :: ' + argtype + ' -> ' + typ + '\n' + func + (' required' if args else ' _') + ' = { ' + ', '.join(values) + ' }\n'

out = ROOT / 'src/Rocksky/API'
out.mkdir(parents=True, exist_ok=True)
header = '-- Generated by scripts/generate.py. Do not edit.\n'
types = [header + 'module Rocksky.Types where\n\nimport Data.Argonaut.Core (Json)\nimport Data.Maybe (Maybe)\n']
for (nsid, key), schema in sorted(defs.items()):
    types.append('type ' + name(nsid, key) + ' = ' + render(schema, nsid, ((nsid,key),)) + '\n')
(ROOT / 'src/Rocksky/Types.purs').write_text('\n'.join(types))
count = 0
for lex in lexicons:
    nsid = lex['id']
    main = lex['defs'].get('main', {})
    if main.get('type') not in ('query', 'procedure'): continue
    group, method = nsid.split('.')[-2:]
    module = 'Rocksky.API.' + cap(group) + '.' + cap(method)
    params = main.get('parameters', {'type':'params','properties':{}})
    input_schema = main.get('input', {}).get('schema')
    output_schema = main.get('output', {}).get('schema', {'type':'unknown'})
    code = header + 'module ' + module + ' where\n\n'
    code += 'import Data.Argonaut.Core (Json)\nimport Data.Either (Either)\nimport Data.Maybe (Maybe(..))\nimport Effect.Aff (Aff)\nimport Rocksky.Client (Client, RockskyError, query, procedure)\nimport Rocksky.Types as Types\n\n'
    code += 'type Params = ' + render(params, nsid) + '\n'
    code += defaults(params, nsid, 'Params', 'defaultParams')
    if input_schema:
        code += '\ntype Input = ' + boundary(input_schema, nsid) + '\n'
        code += defaults(input_schema, nsid, 'Input', 'defaultInput')
    code += '\ntype Output = ' + boundary(output_schema, nsid) + '\n\n'
    code += 'nsid :: String\nnsid = ' + json.dumps(nsid) + '\n\n'
    if main.get('description'):
        code += '-- | ' + main['description'].replace('\n','\n-- | ') + '\n'
    code += 'call :: Client -> Params -> ' + ('Input -> ' if input_schema else '') + 'Aff (Either RockskyError Output)\n'
    if main['type'] == 'query':
        code += 'call client params = query client nsid params\n'
    elif input_schema:
        code += 'call client params input = procedure client nsid params (Just (omitMissing ' + json.dumps(optional_paths(input_schema, nsid)) + ' (encodeJson input)))\n'
        code = code.replace('import Data.Either', 'import Data.Argonaut.Encode (encodeJson)\nimport Rocksky.Internal.Encoding (omitMissing)\nimport Data.Either')
    else:
        code += 'call client params = procedure client nsid params (Nothing :: Maybe Json)\n'
    # Emit only imports actually used by this module.
    body = code[code.index('type Params'):]
    if not re.search(r'\bJson\b', body): code = code.replace('import Data.Argonaut.Core (Json)\n','')
    if 'Types.' not in body: code = code.replace('import Rocksky.Types as Types\n','')
    if 'Maybe' not in body and 'Nothing' not in body and 'Just' not in body: code = code.replace('import Data.Maybe (Maybe(..))\n','')
    if 'Nothing' not in body and 'Just' not in body: code = code.replace('import Data.Maybe (Maybe(..))', 'import Data.Maybe (Maybe)')
    code = code.replace('RockskyError, query, procedure', 'RockskyError, ' + ('query' if main['type']=='query' else 'procedure'))
    path = out / cap(group) / (cap(method) + '.purs')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(code)
    count += 1
print(f'Generated {count} XRPC modules and {len(defs)} shared types.')

subprocess.run(['purs-tidy', 'format-in-place', 'src/Rocksky/API/**/*.purs', 'src/Rocksky/Types.purs'], cwd=ROOT, check=True)
