// Keep REPL functions, help entries and Babashka tasks aligned with package.json.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('purescript/package.json', root), 'utf8'));
const scripts = Object.keys(manifest.scripts).sort();
const names = scripts.map(name => name.replaceAll(':', '-'));
assert.equal(new Set(names).size, names.length, 'Script names collide after replacing colons');
assert.ok(names.every(name => /^[a-z][a-z0-9-]*$/.test(name)), 'Unsupported Clojure function name');
const quote = JSON.stringify;
const namespace = `;; Generated by scripts/register-purescript.mjs; edit purescript/package.json, then regenerate.
(ns console.purescript
  "Every purescript/package.json script. Extra string arguments pass through to Bun."
  (:refer-clojure :exclude [format test])
  (:require [console.shell :as sh]))

(def script-commands
  "[REPL function, package script] pairs used by console help and coverage checks."
  [${scripts.map((script, i) => `[${':' + names[i]} ${quote(script)}]`).join('\n   ')}])

${scripts.map((script, i) => `(defn ${names[i]}
  ${quote(`Run bun run ${script} in purescript/. ${script === 'env:generate' ? ':force resets settings and secrets; other args are forwarded.' : script === 'backfill:jetstream' ? 'Accepts keyword flags and numeric values, e.g. :dry-run :limit 100; strings pass through.' : 'Forwards extra arguments unchanged.'}`)}
  [& args]
  (apply sh/bun "purescript" ${quote(script)} ${script === 'env:generate' ? '(map #(if (= :force %) "--force" %) args)' : script === 'backfill:jetstream' ? '(map #(if (keyword? %) (str "--" (name %)) (str %)) args)' : 'args'}))`).join('\n\n')}
`;
const begin = '  ;; BEGIN GENERATED PURESCRIPT TASKS';
const end = '  ;; END GENERATED PURESCRIPT TASKS';
const tasks = `${begin}
${scripts.map((script, i) => `  ps:${script} {:doc ${quote(`Run purescript: ${script}. Extra arguments pass through to Bun.`)}
    :task (do (require 'console.purescript)
              (apply (resolve 'console.purescript/${names[i]}) *command-line-args*))}`).join('\n')}
${end}`;
const bbPath = new URL('tools/console/bb.edn', root);
let bb = readFileSync(bbPath, 'utf8');
if (bb.includes(begin)) {
  assert.ok(bb.includes(end), 'Missing generated task end marker');
  bb = bb.slice(0, bb.indexOf(begin)) + tasks + bb.slice(bb.indexOf(end) + end.length);
} else {
  const position = bb.indexOf('  ;; ── db ');
  assert.ok(position >= 0, 'Could not locate Babashka task insertion point');
  bb = bb.slice(0, position) + tasks + '\n\n' + bb.slice(position);
}
const check = process.argv.includes('--check');
for (const [path, content] of [[new URL('tools/console/src/console/purescript.clj', root), namespace], [bbPath, bb]]) {
  if (check) assert.equal(readFileSync(path, 'utf8'), content, `Stale registration: ${path.pathname}; run node tools/console/scripts/register-purescript.mjs`);
  else writeFileSync(path, content);
}
console.log(`${check ? 'Verified' : 'Registered'} ${scripts.length} PureScript package scripts for REPL/help/Babashka.`);
