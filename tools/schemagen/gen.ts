#!/usr/bin/env bun
// Emits gleam/src/rocksky_api/schema/<table>.gleam from schema.json (see dump.ts).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const HERE = new URL(".", import.meta.url).pathname;
const OUT = join(HERE, "../../gleam/src/rocksky_api/schema");
mkdirSync(OUT, { recursive: true });

type Col = { prop: string; name: string; columnType: string; notNull: boolean; isArray: boolean };
type Table = { file: string; table: string; columns: Col[] };
const tables: Table[] = JSON.parse(readFileSync(join(HERE, "schema.json"), "utf8"));

const keywords = new Set(["as","assert","case","const","external","fn","if","import","let","opaque","panic","pub","todo","type","use","echo","test","auto","delegate","derive","else","implement","macro"]);
const snake = (s: string) => s.replace(/([A-Z])/g, "_$1").toLowerCase().replace(/^_/, "").replace(/-/g, "_");
const field = (s: string) => (keywords.has(snake(s)) ? snake(s) + "_" : snake(s));
const pascal = (s: string) => s.split(/[_-]/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
function singular(word: string): string {
  if (/(ch|sh|x|ss)es$/.test(word)) return word.slice(0, -2);
  if (/ies$/.test(word)) return word.slice(0, -3) + "y";
  if (/s$/.test(word) && !/ss$/.test(word)) return word.slice(0, -1);
  return word;
}
function typeName(file: string): string {
  const parts = file.split("-");
  parts[parts.length - 1] = singular(parts[parts.length - 1]);
  return pascal(parts.join("-"));
}

const gleamType: Record<string, string> = { PgText: "String", PgInteger: "Int", PgReal: "Float", PgBoolean: "Bool", PgTimestamp: "Timestamp", PgArray: "List(String)", PgJsonb: "Dynamic" };
const decoder: Record<string, string> = { PgText: "decode.string", PgInteger: "row.int()", PgReal: "row.float()", PgBoolean: "decode.bool", PgTimestamp: "row.timestamp()", PgArray: "row.strings()", PgJsonb: "row.jsonb()" };
const encoder: Record<string, string> = { PgText: "json.string", PgInteger: "json.int", PgReal: "json.float", PgBoolean: "json.bool", PgTimestamp: "encode_timestamp", PgArray: "encode_strings", PgJsonb: "encode_dynamic" };

for (const t of tables) {
  const T = typeName(t.file);
  const mod = t.file.replace(/-/g, "_");
  const needsTs = t.columns.some((c) => c.columnType === "PgTimestamp");
  const needsDyn = t.columns.some((c) => c.columnType === "PgJsonb");
  const needsOpt = t.columns.some((c) => !c.notNull);
  const fields = t.columns.map((c) => {
    const base = gleamType[c.columnType] ?? "Dynamic";
    return `${field(c.prop)}: ${c.notNull ? base : `Option(${base})`}`;
  });
  const decodeLines = t.columns.map((c) => {
    const d = c.name === "xata_version" && c.columnType === "PgText"
      ? "row.version_string()"
      : decoder[c.columnType] ?? "decode.dynamic";
    return c.notNull
      ? `  use ${field(c.prop)} <- decode.field(${JSON.stringify(c.name)}, ${d})`
      : `  use ${field(c.prop)} <- decode.optional_field(${JSON.stringify(c.name)}, None, decode.optional(${d}))`;
  });
  const construct = `${T}(${t.columns.map((c) => `${field(c.prop)}:`).join(", ")})`;
  const encodeLines = t.columns.map((c) => {
    const e = encoder[c.columnType] ?? "encode_dynamic";
    return c.notNull
      ? `    #(${JSON.stringify(c.prop)}, ${e}(value.${field(c.prop)})),`
      : `    #(${JSON.stringify(c.prop)}, json.nullable(value.${field(c.prop)}, ${e})),`;
  });
  const imports = [
    needsDyn ? "import gleam/dynamic.{type Dynamic}" : null,
    "import gleam/dynamic/decode.{type Decoder}",
    "import gleam/json.{type Json}",
    "import gleam/list",
    needsOpt ? "import gleam/option.{type Option, None}" : "import gleam/option.{type Option}",
    "import gleam/string",
    needsTs ? "import gleam/time/timestamp.{type Timestamp}" : null,
    "import rocksky_api/db/row",
  ].filter(Boolean).join("\n");
  const helpers = [
    needsTs ? `fn encode_timestamp(t: Timestamp) -> Json {\n  json.string(row.iso8601(t))\n}` : null,
    t.columns.some((c) => c.columnType === "PgArray") ? `fn encode_strings(items: List(String)) -> Json {\n  json.array(items, json.string)\n}` : null,
    needsDyn ? `fn encode_dynamic(d: Dynamic) -> Json {\n  row.dynamic_to_json(d)\n}` : null,
  ].filter(Boolean).join("\n\n");

  const src = `//// \`${t.table}\` table. Generated by tools/schemagen; do not edit.

${imports}

pub const table = ${JSON.stringify(t.table)}

pub type ${T} {
  ${T}(
    ${fields.join(",\n    ")},
  )
}

pub const column_names = [${t.columns.map((c) => JSON.stringify(c.name)).join(", ")}]

/// \`alias.col1, alias.col2, …\` for a SELECT list.
pub fn columns(alias: String) -> String {
  column_names
  |> list.map(fn(c) { alias <> "." <> c })
  |> string.join(", ")
}

/// Decodes a row whose keys are the table's column names.
pub fn decoder() -> Decoder(${T}) {
${decodeLines.join("\n")}
  decode.success(${construct})
}

/// Decodes a row nested under \`key\` (\`to_jsonb(alias) AS key\`).
pub fn nested(key: String) -> Decoder(${T}) {
  decode.at([key], decoder())
}

pub fn optional_nested(key: String) -> Decoder(Option(${T})) {
  decode.at([key], decode.optional(decoder()))
}

/// The row as JSON with camelCase keys, as the TypeScript API returned it.
pub fn to_json(value: ${T}) -> Json {
  json.object([
${encodeLines.join("\n")}
  ])
}
${helpers ? "\n" + helpers + "\n" : ""}`;
  writeFileSync(join(OUT, `${mod}.gleam`), src.replace(/import gleam\/option\.\{type Option, None\}/, "import gleam/option.{type Option, None}"));
}
console.log(`wrote ${tables.length} schema modules to ${OUT}`);
