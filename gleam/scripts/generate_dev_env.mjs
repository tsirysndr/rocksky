function quote(value) {
  value = String(value);
  for (const delimiter of ["'", '`', '"']) if (!value.includes(delimiter)) return delimiter + value + delimiter;
  throw new Error('An existing value cannot be safely encoded as dotenv');
}

export function generate(config, file, {force = false} = {}) {
  const local = localSettings(config);
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  const previous = force ? {} : dotenv.parse(existing ?? '');
  const values = {
    SPOTIFY_CLIENT_ID: '', SPOTIFY_CLIENT_SECRET: '', DROPBOX_CLIENT_ID: '', DROPBOX_CLIENT_SECRET: '',
    ROCKSKY_BETA_TOKEN: '', S3_ACCESS_KEY_ID: '', S3_SECRET_ACCESS_KEY: '', S3_REGION: 'us-east-1',
    S3_BUCKET_NAME: 'rocksky-library', S3_COVERS_BUCKET_NAME: 'rocksky', ...previous, ...local,
  };
  for (const key of ['COOKIE_SECRET', 'JWT_SECRET', 'STORAGE_ENCRYPTION_KEY', 'SPOTIFY_ENCRYPTION_KEY', 'SUBMISSIONS_SECRET']) {
    if (!values[key]) values[key] = randomBytes(32).toString('hex');
  }
  if (!values.SPOTIFY_ENCRYPTION_IV) values.SPOTIFY_ENCRYPTION_IV = randomBytes(16).toString('hex');
  for (const key of ['PRIVATE_KEY_1', 'PRIVATE_KEY_2', 'PRIVATE_KEY_3']) {
    if (!values[key]) values[key] = generateKeyPairSync('ec', {
      namedCurve: 'prime256v1', privateKeyEncoding: {type: 'pkcs8', format: 'pem'}, publicKeyEncoding: {type: 'spki', format: 'pem'},
    }).privateKey;
  }
  const content = '# Generated by bun run dev:env from ../compose.yaml. Local development only.\n'
    + '# Blank provider credentials need configuration. S3 and application sidecars are not in Compose.\n'
    + Object.entries(values).map(([key, value]) => `${key}=${quote(value)}`).join('\n') + '\n';
  const parsed = dotenv.parse(content);
  for (const [key, value] of Object.entries(values)) if (parsed[key] !== String(value)) throw new Error(`Cannot preserve dotenv value for ${key}`);
  if (existing === content) return false;
  if (existing !== null) fs.writeFileSync(`${file}.local-dev-${Date.now()}.bak`, existing, {mode: 0o600, flag: 'wx'});
  fs.writeFileSync(file, content, {mode: 0o600});
  fs.chmodSync(file, 0o600);
  return true;
}

