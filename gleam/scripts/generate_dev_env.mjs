function endpoint(service, target) {
  const port = service?.ports?.find(p => Number(p.target) === target && (p.protocol ?? 'tcp') === 'tcp');
  if (!port || !/^\d+$/.test(String(port.published))) throw new Error(`Compose must publish TCP port ${target}`);
  let host = port.host_ip;
  if (!host || host === '0.0.0.0' || host === '::') host = '127.0.0.1';
  return {host, port: String(port.published), authority: `${host.includes(':') ? `[${host}]` : host}:${port.published}`};
}

