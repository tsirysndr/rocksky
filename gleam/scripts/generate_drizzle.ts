import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { getTableColumns, getTableName } from 'drizzle-orm';
import schema from '../../apps/api/src/schema';
const completeSchema = {...schema};

const root = new URL('../', import.meta.url);
const out = new URL('src/rocksky_api/drizzle/schema/', root);
mkdirSync(out, {recursive:true});
const keywords = new Set(['as','assert','case','const','external','fn','if','import','let','opaque','panic','pub','todo','type','use','echo','test','auto','delegate','derive','else','implement','macro']);
const snake = (s:string) => s.replace(/([A-Z])/g,'_$1').toLowerCase().replace(/^_/,'').replaceAll('-','_');
const field = (s:string) => keywords.has(snake(s)) ? `${snake(s)}_` : snake(s);
const codecs:Record<string,[string,string]> = {
  PgText:['String','text'], PgInteger:['Int','integer'], PgReal:['Float','real'],
  PgBoolean:['Bool','boolean'], PgTimestamp:['Timestamp','timestamp'],
  PgArray:['List(String)','text_array'], PgJsonb:['Dynamic','jsonb'],
};
let generated = 0;
for (const table of Object.values(completeSchema)) {
  const name = getTableName(table);
  const module = name;
  const columns = Object.entries(getTableColumns(table));
  const rowSource = readFileSync(new URL(`src/rocksky_api/schema/${module}.gleam`,root),'utf8');
  const rowType = /pub type (\w+)/.exec(rowSource)![1];
  const localNames = new Set(['table', ...columns.map(([property]) => field(property))]);
  const used = new Set(['table','column', ...columns.map(([,c]) => {
    const info=codecs[c.columnType];
    if(!info) throw new Error(`Unsupported column ${name}.${c.name}: ${c.columnType}`);
    return info[1];
  })]);
  if(columns.some(([,c])=>!c.notNull)) used.add('optional');
  const imported = (name:string) => localNames.has(name) ? `db_${name}` : name;
  const imports = ['type Expression','type Table',...Array.from(used).sort().map(name=>name===imported(name)?name:`${name} as ${imported(name)}`)].join(', ');
  let code = `//// Generated by scripts/generate_drizzle.ts from the TypeScript Drizzle schema.\n\nimport rocksky_api/drizzle/orm.{${imports}}\nimport rocksky_api/schema/${module} as rows\n`;
  if (columns.some(([,c]) => !c.notNull)) code+='import gleam/option.{type Option}\n';
  if (columns.some(([,c]) => c.dataType==='date')) code+='import gleam/time/timestamp.{type Timestamp}\n';
  if (columns.some(([,c]) => c.dataType==='json')) code+='import gleam/dynamic.{type Dynamic}\n';
  code+=`\npub fn table() -> Table(rows.${rowType}) {\n  ${imported("table")}("${name}", rows.decoder())\n}\n`;
  for (const [property,c] of columns) {
    const info=codecs[c.columnType];
    if(!info) throw new Error(`Unsupported column ${name}.${property}: ${c.columnType}`);
    const [type,codecName]=info;
    const codec=`${imported(codecName)}()`;
    const result=c.notNull?type:`Option(${type})`;
    code+=`\npub fn ${field(property)}(table: Table(rows.${rowType})) -> Expression(${result}) {\n  ${imported("column")}(table, "${property}", ${c.notNull?codec:`${imported("optional")}(${codec})`})\n}\n`;
  }
  writeFileSync(new URL(`${module}.gleam`,out),code);
  generated++;
}
const build = await Bun.build({entrypoints:[new URL('scripts/drizzle_schema_entry.ts',root).pathname],target:'node',format:'esm',external:['drizzle-orm','drizzle-orm/*'],minify:false});
if(!build.success) throw new Error(build.logs.join('\n'));
writeFileSync(new URL('src/rocksky_api/drizzle/schema_ffi.mjs',root), await build.outputs[0].text());
const formatted = Bun.spawn(['gleam','format', new URL('src/rocksky_api/drizzle/schema',root).pathname],{stdout:'inherit',stderr:'inherit'});
if(await formatted.exited !== 0) throw new Error('Failed to format generated bindings');
console.log(`Generated ${generated} Gleam Drizzle table modules and bundled runtime schema.`);
